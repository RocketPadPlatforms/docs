import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';
import { parseSources } from './config';
import { LOCAL_SIDEBARS_DIR, parseLocalArgs, prepareLocalSidebars } from './local';

const config = parseSources({
  apps: [
    {
      id: 'app-a',
      label: 'A',
      description: 'd',
      repo: 'o/app-a',
      docsPath: 'docs',
      sidebarFile: 'docs/sidebars.json',
    },
  ],
});

describe('local mode helpers', () => {
  const dir = mkdtempSync(join(tmpdir(), 'local-'));
  afterAll(() => rmSync(dir, { recursive: true, force: true }));
  mkdirSync(join(dir, 'app/docs'), { recursive: true });

  it('resolves existing folders and rejects unknown apps or missing folders', () => {
    expect(parseLocalArgs(['app-a=app/docs'], config, dir)).toEqual([
      ['app-a', join(dir, 'app/docs')],
    ]);
    expect(() => parseLocalArgs(['nope=app/docs'], config, dir)).toThrow(/not in docs-sources/);
    expect(() => parseLocalArgs(['app-a=missing'], config, dir)).toThrow(/not a directory/);
    expect(() => parseLocalArgs(['app-a'], config, dir)).toThrow(/<app-id>=<path>/);
    expect(() => parseLocalArgs([], config, dir)).toThrow(/usage/);
  });

  it('writes a normalized sidebar for the working copy, autogenerated when there is none', async () => {
    const entries = [['app-a', join(dir, 'app/docs')] as const];
    await prepareLocalSidebars(entries, config, dir);
    const file = join(dir, LOCAL_SIDEBARS_DIR, 'app-a.json');
    expect(JSON.parse(readFileSync(file, 'utf8'))).toEqual({
      docs: [{ type: 'autogenerated', dirName: '.' }],
    });

    writeFileSync(join(dir, 'app/docs/sidebars.json'), JSON.stringify({ main: ['intro'] }));
    await prepareLocalSidebars(entries, config, dir);
    expect(JSON.parse(readFileSync(file, 'utf8'))).toEqual({ docs: ['intro'] });
  });
});
