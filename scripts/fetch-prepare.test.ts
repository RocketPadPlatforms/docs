import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { createRepo, createStandardFixtures, revParse } from '../tests/helpers/fixtures';
import { authEnv, fetchVersion, redact } from './fetch-docs';
import { loadSources } from './lib/config';
import { readLock, writeLock } from './lib/lock';
import { LocalGitProvider } from './lib/providers/local-git';
import { runSync } from './lib/sync';
import { prepare } from './prepare-docs';

const json = (p: string) => JSON.parse(readFileSync(p, 'utf8'));

describe('fetch + prepare against local-git fixtures', () => {
  let root: string; // fixture repos
  let site: string; // fake site dir
  const savedBase = process.env.DOCS_GIT_BASE;

  beforeAll(async () => {
    root = resolve(mkdtempSync(join(tmpdir(), 'docs-fx-')));
    site = resolve(mkdtempSync(join(tmpdir(), 'docs-site-')));
    process.env.DOCS_GIT_BASE = pathToFileURL(root).href;
    await createStandardFixtures(root);

    const sources = {
      apps: ['app-a', 'app-b'].map((id) => ({
        id,
        label: id,
        description: `${id} description`,
        repo: `RocketPadPlatforms/${id}`,
        docsPath: 'docs',
        sidebarFile: 'docs/sidebars.json',
      })),
    };
    writeFileSync(join(site, 'docs-sources.json'), JSON.stringify(sources));
    const out = await runSync({
      config: loadSources(join(site, 'docs-sources.json')),
      lock: readLock(join(site, 'nope.json')),
      provider: new LocalGitProvider(),
    });
    writeLock(out.lock, join(site, 'docs-versions.lock.json'));
  });

  afterAll(() => {
    process.env.DOCS_GIT_BASE = savedBase;
    rmSync(root, { recursive: true, force: true });
    rmSync(site, { recursive: true, force: true });
  });

  it('fetches by commit, caches, and leaves no .git behind', async () => {
    const config = loadSources(join(site, 'docs-sources.json'));
    const lock = readLock(join(site, 'docs-versions.lock.json'));
    const sourcesDir = join(site, '.cache/sources');
    for (const app of config.apps) {
      for (const v of lock.apps[app.id].versions) {
        const target = { app, version: v.version, commit: v.commit };
        expect(await fetchVersion(target, { root: sourcesDir })).toBe('fetched');
        expect(await fetchVersion(target, { root: sourcesDir })).toBe('cached');
        const dir = join(sourcesDir, app.id, v.commit);
        expect(existsSync(join(dir, '.git'))).toBe(false);
        expect(existsSync(join(dir, 'docs/index.md'))).toBe(true);
      }
    }
    // no half-finished temp dirs
    expect(readdirSync(join(sourcesDir, 'app-a')).every((n) => !n.startsWith('.tmp'))).toBe(true);
  });

  it('prepares the Docusaurus versioned layout', async () => {
    const index = await prepare({ cwd: site, sources: join(site, '.cache/sources') });
    expect(index.apps.map((a) => [a.id, a.latest, a.versions])).toEqual([
      ['app-a', '0.2.0', ['0.2.0', '0.1.0']],
      ['app-b', '0.2.0', ['0.2.0', '0.1.0']],
    ]);
    expect(json(join(site, 'app-a_versions.json'))).toEqual(['0.2.0', '0.1.0']);
    expect(existsSync(join(site, 'app-a_versioned_docs/version-0.1.0/only-in-old.md'))).toBe(true);
    // JSON sidebar as-is, JS sidebar evaluated + renamed, missing sidebar autogenerated
    const sb = (id: string, v: string) =>
      json(join(site, `${id}_versioned_sidebars/version-${v}-sidebars.json`));
    expect(sb('app-a', '0.1.0')).toEqual({ docs: ['intro', 'guide', 'only-in-old'] });
    expect(sb('app-a', '0.2.0')).toEqual({ docs: ['intro', 'guide', 'new-feature'] });
    expect(sb('app-b', '0.2.0')).toEqual({ docs: [{ type: 'autogenerated', dirName: '.' }] });
    expect(json(join(site, 'generated/docs-index.json')).apps).toHaveLength(2);
  });

  it('fails with a pointer to fetch when sources are missing', async () => {
    await expect(prepare({ cwd: site, sources: join(site, 'empty') })).rejects.toThrow(
      /fetch:docs/,
    );
  });

  it('rejects symlinks in fetched docs', async () => {
    const repo = 'RocketPadPlatforms/app-evil';
    await createRepo(root, repo, [
      { tag: 'v1.0.0', files: { 'docs/a.md': 'x' }, symlinks: { 'docs/leak.md': '/etc/passwd' } },
    ]);
    const sha = await revParse(root, repo, 'HEAD');
    const app = loadSources(join(site, 'docs-sources.json')).apps[0];
    await expect(
      fetchVersion(
        { app: { ...app, id: 'app-evil', repo }, version: '1.0.0', commit: sha },
        { root: join(site, '.cache/evil') },
      ),
    ).rejects.toThrow(/symlink/);
  });

  it('never leaks the token when a fetch fails', async () => {
    const token = 'ghs_super_secret_token_value';
    process.env.DOCS_GIT_BASE = 'https://127.0.0.1:1';
    try {
      const app = loadSources(join(site, 'docs-sources.json')).apps[0];
      const err = await fetchVersion(
        { app, version: '9.9.9', commit: 'f'.repeat(40) },
        { root: join(site, '.cache/leak'), token },
      ).catch((e: Error) => e);
      expect(err).toBeInstanceOf(Error);
      const basic = Buffer.from(`x-access-token:${token}`).toString('base64');
      expect((err as Error).message).not.toContain(token);
      expect((err as Error).message).not.toContain(basic);
    } finally {
      process.env.DOCS_GIT_BASE = pathToFileURL(root).href;
    }
  });
});

describe('authEnv / redact', () => {
  it('passes the token only via scoped GIT_CONFIG env, appended after existing entries', () => {
    const env = authEnv('tok', 'https://github.com', { GIT_CONFIG_COUNT: '2' });
    expect(env.GIT_CONFIG_COUNT).toBe('3');
    expect(env.GIT_CONFIG_KEY_2).toBe('http.https://github.com/.extraheader');
    expect(env.GIT_CONFIG_VALUE_2).toMatch(/^AUTHORIZATION: basic /);
    expect(JSON.stringify(env)).not.toContain('"tok"');
  });

  it('adds nothing without a token or for file:// bases', () => {
    expect(authEnv(undefined, 'https://github.com')).toEqual({});
    expect(authEnv('tok', 'file:///x')).toEqual({});
  });

  it('redacts raw and base64 forms', () => {
    const basic = Buffer.from('x-access-token:tok').toString('base64');
    expect(redact(`a tok b ${basic}`, 'tok')).toBe('a *** b ***');
  });
});
