import { mkdirSync, readdirSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { git } from '../../scripts/lib/git';

const IDENTITY = {
  GIT_AUTHOR_NAME: 'Fixture',
  GIT_AUTHOR_EMAIL: 'fixture@example.com',
  GIT_COMMITTER_NAME: 'Fixture',
  GIT_COMMITTER_EMAIL: 'fixture@example.com',
  GIT_CONFIG_COUNT: '2',
  GIT_CONFIG_KEY_0: 'commit.gpgsign',
  GIT_CONFIG_VALUE_0: 'false',
  GIT_CONFIG_KEY_1: 'tag.gpgsign',
  GIT_CONFIG_VALUE_1: 'false',
};

export interface FixtureRelease {
  /** tag name, e.g. v0.1.0 */
  tag: string;
  /** complete file tree of the repo at this tag */
  files: Record<string, string>;
  annotated?: boolean;
  /** path -> link target, for testing that symlinks in app docs are rejected */
  symlinks?: Record<string, string>;
}

const run = (cwd: string, args: string[]) => git(args, { cwd, env: IDENTITY });

/** Creates `<root>/<repo>` as a git repo and commits + tags every release in order. */
export async function createRepo(root: string, repo: string, releases: FixtureRelease[]) {
  const dir = join(root, repo);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  await run(dir, ['init', '-q', '-b', 'main']);
  // GitHub serves blob-filtered fetches of arbitrary SHAs; mirror that for file:// remotes
  await run(dir, ['config', 'uploadpack.allowFilter', 'true']);
  await run(dir, ['config', 'uploadpack.allowAnySHA1InWant', 'true']);
  for (const r of releases) await addRelease(root, repo, r);
  return dir;
}

export async function addRelease(root: string, repo: string, r: FixtureRelease) {
  const dir = join(root, repo);
  for (const entry of readdirSync(dir)) {
    if (entry !== '.git') rmSync(join(dir, entry), { recursive: true, force: true });
  }
  for (const [path, content] of Object.entries(r.files)) {
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    writeFileSync(join(dir, path), content);
  }
  for (const [path, target] of Object.entries(r.symlinks ?? {})) {
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    symlinkSync(target, join(dir, path));
  }
  await run(dir, ['add', '-A']);
  await run(dir, ['commit', '-q', '--allow-empty', '-m', `release ${r.tag}`]);
  await run(dir, r.annotated ? ['tag', '-a', r.tag, '-m', r.tag] : ['tag', r.tag]);
  return (await run(dir, ['rev-parse', 'HEAD'])).trim();
}

/** Re-points an existing tag at a new commit (simulates a moved tag). */
export async function moveTag(
  root: string,
  repo: string,
  tag: string,
  files: Record<string, string>,
) {
  const dir = join(root, repo);
  for (const [path, content] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    writeFileSync(join(dir, path), content);
  }
  await run(dir, ['add', '-A']);
  await run(dir, ['commit', '-q', '-m', `rewrite ${tag}`]);
  await run(dir, ['tag', '-f', tag]);
  return (await run(dir, ['rev-parse', 'HEAD'])).trim();
}

export async function deleteTag(root: string, repo: string, tag: string) {
  await run(join(root, repo), ['tag', '-d', tag]);
}

export async function revParse(root: string, repo: string, rev: string) {
  return (await run(join(root, repo), ['rev-parse', rev])).trim();
}

const doc = (id: string, title: string, body: string, extra = '') =>
  `---\nid: ${id}\ntitle: ${title}\ndescription: ${title} documentation.\n${extra}---\n\n# ${title}\n\n${body}\n`;

/** Docs for the two standard fixture apps. `tag` decides which page set exists. */
export function appAFiles(version: '0.1.0' | '0.2.0'): Record<string, string> {
  const common = {
    'docs/index.md': doc('intro', 'App A', `Start page of ${version}.`, 'slug: /\n'),
    'docs/guide.md': doc('guide', 'Guide', `Guide for ${version}. See [intro](./index.md).`),
  };
  return version === '0.1.0'
    ? {
        ...common,
        'docs/only-in-old.md': doc('only-in-old', 'Only in old', 'Gone in 0.2.0.'),
        'docs/sidebars.json': JSON.stringify({ docs: ['intro', 'guide', 'only-in-old'] }),
      }
    : {
        ...common,
        'docs/new-feature.md': doc('new-feature', 'New feature', 'Added in 0.2.0.'),
        // JS sidebar with a single non-"docs" key: prepare must evaluate and rename it
        'docs/sidebars.js': "module.exports = { main: ['intro', 'guide', 'new-feature'] };\n",
      };
}

export function appBFiles(version: '0.1.0' | '0.2.0'): Record<string, string> {
  // no sidebar file at all: prepare generates an autogenerated sidebar
  return {
    'docs/index.md': doc('index', 'App B', `Start page of ${version}.`, 'slug: /\n'),
    'docs/usage.md': doc('usage', 'Usage', `Usage for ${version}.`),
  };
}

export async function createStandardFixtures(root: string) {
  await createRepo(root, 'RocketPadPlatforms/app-a', [
    { tag: 'v0.1.0', files: appAFiles('0.1.0') },
    { tag: 'v0.2.0', files: appAFiles('0.2.0'), annotated: true },
  ]);
  await createRepo(root, 'RocketPadPlatforms/app-b', [
    { tag: 'v0.1.0', files: appBFiles('0.1.0') },
    { tag: 'v0.2.0', files: appBFiles('0.2.0'), annotated: true },
  ]);
}

