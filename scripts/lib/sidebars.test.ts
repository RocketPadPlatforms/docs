import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';
import { AUTOGENERATED, findSidebarFile, loadSidebars, normalizeSidebars } from './sidebars';

describe('normalizeSidebars', () => {
  it('keeps a sidebar already named docs', () => {
    const s = { docs: ['a'], other: ['b'] };
    expect(normalizeSidebars(s, 'x')).toEqual(s);
  });

  it('renames a single sidebar with another key to docs', () => {
    expect(normalizeSidebars({ tutorialSidebar: ['a', 'b'] }, 'x')).toEqual({ docs: ['a', 'b'] });
  });

  it('errors naming app and version when several sidebars have no docs', () => {
    expect(() => normalizeSidebars({ a: [], b: [] }, 'app-a@0.3.0')).toThrow(
      /app-a@0\.3\.0.*several sidebars \(a, b\).*"docs"/,
    );
  });

  it('rejects empty, function and non-object sidebars', () => {
    expect(() => normalizeSidebars({}, 'x')).toThrow(/no sidebars/);
    expect(() => normalizeSidebars(() => ({}), 'x')).toThrow(/function/);
    expect(() => normalizeSidebars({ docs: [{ type: 'html', value: () => 1 }] }, 'x')).toThrow(
      /function/,
    );
    expect(() => normalizeSidebars([], 'x')).toThrow(/object/);
  });
});

describe('loadSidebars', () => {
  const root = mkdtempSync(join(tmpdir(), 'docs-sidebars-'));
  afterAll(() => rmSync(root, { recursive: true, force: true }));
  mkdirSync(join(root, 'docs'));

  it('is autogenerated when no sidebar file exists', async () => {
    expect(await loadSidebars(root, 'docs/sidebars.json', 'x')).toEqual(AUTOGENERATED);
    expect(await loadSidebars(root, undefined, 'x')).toEqual(AUTOGENERATED);
  });

  it('evaluates JS sidebars and normalizes them', async () => {
    writeFileSync(
      join(root, 'docs/sidebars.js'),
      "const items = ['a']; module.exports = { main: items };\n",
    );
    // configured as .json but only .js exists: sibling lookup finds it
    expect(findSidebarFile(root, 'docs/sidebars.json')).toBe(join(root, 'docs/sidebars.js'));
    expect(await loadSidebars(root, 'docs/sidebars.json', 'x')).toEqual({ docs: ['a'] });
  });

  it('evaluates TS sidebars with a default export', async () => {
    mkdirSync(join(root, 't/docs'), { recursive: true });
    writeFileSync(
      join(root, 't/docs/sidebars.ts'),
      "const s: Record<string, string[]> = { docs: ['x'] };\nexport default s;\n",
    );
    expect(await loadSidebars(join(root, 't'), 'docs/sidebars.ts', 'x')).toEqual({ docs: ['x'] });
  });

  it('prefers the exact configured file and uses JSON as-is', async () => {
    mkdirSync(join(root, 'j/docs'), { recursive: true });
    writeFileSync(join(root, 'j/docs/sidebars.json'), JSON.stringify({ docs: ['j'], more: [] }));
    expect(await loadSidebars(join(root, 'j'), 'docs/sidebars.json', 'x')).toEqual({
      docs: ['j'],
      more: [],
    });
  });
});
