import { existsSync, readFileSync } from 'node:fs';
import { dirname, extname, join } from 'node:path';
import { createJiti } from 'jiti';

export type SidebarsJson = Record<string, unknown>;

export const AUTOGENERATED: SidebarsJson = {
  docs: [{ type: 'autogenerated', dirName: '.' }],
};

const CODE_EXT = new Set(['.js', '.cjs', '.mjs', '.ts', '.cts', '.mts']);
const SIBLINGS = ['sidebars.json', 'sidebars.js', 'sidebars.cjs', 'sidebars.mjs', 'sidebars.ts'];

/**
 * The configured file, else a sibling named sidebars.*. Handles an app that moved
 * from sidebars.js to sidebars.json between releases.
 */
export function findSidebarFile(root: string, configured: string | undefined): string | null {
  if (!configured) return null;
  const exact = join(root, configured);
  if (existsSync(exact)) return exact;
  for (const name of SIBLINGS) {
    const candidate = join(root, dirname(configured), name);
    if (existsSync(candidate)) return candidate;
  }
  return null;
}

/** JSON is parsed as-is; JS/TS is evaluated (this runs app code, only ever without secrets). */
export async function readSidebars(file: string): Promise<unknown> {
  if (extname(file) === '.json') return JSON.parse(readFileSync(file, 'utf8'));
  if (!CODE_EXT.has(extname(file))) throw new Error(`unsupported sidebar file type: ${file}`);
  // the file sits under the site directory, so its requires resolve to the site's node_modules
  const jiti = createJiti(import.meta.url, { interopDefault: true, moduleCache: false });
  return jiti.import(file, { default: true });
}

function toJson(value: unknown): SidebarsJson {
  if (typeof value === 'function') {
    throw new Error('sidebar file exports a function; export a plain object instead');
  }
  const text = JSON.stringify(value, (_k, v) => {
    if (typeof v === 'function')
      throw new Error('sidebar contains a function and cannot be serialized');
    return v;
  });
  const parsed: unknown = JSON.parse(text ?? 'null');
  if (parsed === null || typeof parsed !== 'object' || Array.isArray(parsed)) {
    throw new Error('sidebar file must export an object of sidebars');
  }
  return parsed as SidebarsJson;
}

/** Every version needs a sidebar with id `docs`. */
export function normalizeSidebars(raw: unknown, where: string): SidebarsJson {
  let sidebars: SidebarsJson;
  try {
    sidebars = toJson(raw);
  } catch (err) {
    throw new Error(`${where}: ${err instanceof Error ? err.message : err}`);
  }
  const ids = Object.keys(sidebars);
  if (ids.includes('docs')) return sidebars;
  if (ids.length === 1) return { docs: sidebars[ids[0]] };
  if (ids.length === 0) throw new Error(`${where}: sidebar file defines no sidebars`);
  throw new Error(
    `${where}: sidebar file defines several sidebars (${ids.join(', ')}) but none is named "docs"; rename one to "docs"`,
  );
}

export async function loadSidebars(
  root: string,
  configured: string | undefined,
  where: string,
): Promise<SidebarsJson> {
  const file = findSidebarFile(root, configured);
  if (!file) return AUTOGENERATED;
  return normalizeSidebars(await readSidebars(file), `${where} (${file.slice(root.length + 1)})`);
}
